CREATE TABLE tb_matricula (
    id_matricula      integer      GENERATED BY DEFAULT AS IDENTITY,
    id_aluno          integer      NOT NULL,
    id_turma          integer      NOT NULL,
    data_matricula    timestamptz  NOT NULL DEFAULT now(),
    status_matricula  status_mat_t NOT NULL,              -- trancar/cancelar muda status, não apaga

    CONSTRAINT pk_matricula PRIMARY KEY (id_matricula),
    CONSTRAINT uq_matricula_aluno_turma UNIQUE (id_aluno, id_turma),  -- sem duplicata na contagem de vagas
    CONSTRAINT ck_matricula_data_nao_futura CHECK (data_matricula <= now()),
    CONSTRAINT fk_matricula_aluno FOREIGN KEY (id_aluno) REFERENCES tb_aluno (id_aluno)
        ON DELETE RESTRICT ON UPDATE CASCADE,               -- preserva o registro acadêmico
    CONSTRAINT fk_matricula_turma FOREIGN KEY (id_turma) REFERENCES tb_turma (id_turma)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE tb_pre_requisito (
    id_curriculo             integer   NOT NULL,
    id_disciplina            integer   NOT NULL,          -- disciplina que exige
    id_disciplina_requisito  integer   NOT NULL,          -- disciplina exigida
    vinculo_pre_requisito    vinculo_t NOT NULL,

    CONSTRAINT pk_pre_requisito PRIMARY KEY (id_curriculo, id_disciplina, id_disciplina_requisito),
    CONSTRAINT ck_pre_requisito_sem_autorreferencia         -- barra A → A, não ciclos maiores
        CHECK (id_disciplina <> id_disciplina_requisito),
    CONSTRAINT fk_pre_requisito_disciplina                  -- composta: disciplina está na grade
        FOREIGN KEY (id_curriculo, id_disciplina)
        REFERENCES tb_curriculo_disciplina (id_curriculo, id_disciplina)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_pre_requisito_requisito                   -- composta: requisito na MESMA grade
        FOREIGN KEY (id_curriculo, id_disciplina_requisito)
        REFERENCES tb_curriculo_disciplina (id_curriculo, id_disciplina)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

