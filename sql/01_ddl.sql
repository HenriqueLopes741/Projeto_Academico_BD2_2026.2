CREATE TABLE tb_turma_horario (
    id_turma_horario          integer   GENERATED BY DEFAULT AS IDENTITY,
    id_turma                  integer   NOT NULL,
    id_periodo_letivo         smallint  NOT NULL,         -- cópia do período da turma, usada pelo EXCLUDE
    id_sala                   integer   NOT NULL,
    dia_semana_turma_horario  smallint  NOT NULL,         -- ISO: 1 = segunda ... 7 = domingo
    faixa_turma_horario       timerange NOT NULL,         -- sempre [)

    CONSTRAINT pk_turma_horario PRIMARY KEY (id_turma_horario),
    CONSTRAINT ck_turma_horario_dia_semana CHECK (dia_semana_turma_horario BETWEEN 1 AND 7),
    CONSTRAINT ck_turma_horario_faixa_valida                -- com início e fim, não vazia
        CHECK (NOT isempty(faixa_turma_horario)
           AND lower(faixa_turma_horario) IS NOT NULL
           AND upper(faixa_turma_horario) IS NOT NULL),
    CONSTRAINT ex_turma_horario_sala_ocupada                -- mesma sala, período e dia sem faixas sobrepostas
        EXCLUDE USING gist (
            id_sala                  WITH =,
            id_periodo_letivo        WITH =,
            dia_semana_turma_horario WITH =,
            faixa_turma_horario      WITH &&
        ),
    CONSTRAINT fk_turma_horario_turma                       -- composta: período tem de ser o da turma
        FOREIGN KEY (id_turma, id_periodo_letivo)
        REFERENCES tb_turma (id_turma, id_periodo_letivo)
        ON DELETE CASCADE ON UPDATE CASCADE,                -- horário é parte da turma
    CONSTRAINT fk_turma_horario_sala FOREIGN KEY (id_sala) REFERENCES tb_sala (id_sala)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

