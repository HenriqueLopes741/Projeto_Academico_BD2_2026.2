CREATE TABLE tb_turma (
    id_turma           integer     GENERATED BY DEFAULT AS IDENTITY,
    id_disciplina      integer     NOT NULL,
    id_periodo_letivo  smallint    NOT NULL,
    id_professor       integer     NOT NULL,
    codigo_turma       varchar(15) NOT NULL,
    vagas_turma        smallint    NOT NULL,              -- limite de matrículas: controlado por transação (Marco 2)
    turno_turma        turno_t     NOT NULL,

    CONSTRAINT pk_turma PRIMARY KEY (id_turma),
    CONSTRAINT uq_turma_periodo_codigo UNIQUE (id_periodo_letivo, codigo_turma),  -- código se repete a cada semestre
    CONSTRAINT uq_turma_id_periodo     UNIQUE (id_turma, id_periodo_letivo),      -- alvo da FK composta de tb_turma_horario
    CONSTRAINT ck_turma_codigo_preenchido CHECK (length(btrim(codigo_turma)) > 0),
    CONSTRAINT ck_turma_vagas             CHECK (vagas_turma BETWEEN 1 AND 300),
    CONSTRAINT fk_turma_disciplina FOREIGN KEY (id_disciplina)
        REFERENCES tb_disciplina (id_disciplina) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_turma_periodo_letivo FOREIGN KEY (id_periodo_letivo)
        REFERENCES tb_periodo_letivo (id_periodo_letivo) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_turma_professor FOREIGN KEY (id_professor)
        REFERENCES tb_professor (id_professor) ON DELETE RESTRICT ON UPDATE CASCADE
);

