    CONSTRAINT ck_curriculo_disciplina_periodo CHECK (periodo_curriculo_disciplina BETWEEN 1 AND 20),
    CONSTRAINT fk_curriculo_disciplina_curriculo FOREIGN KEY (id_curriculo)
