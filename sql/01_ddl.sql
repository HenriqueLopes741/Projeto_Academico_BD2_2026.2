CREATE TABLE tb_aluno (
    id_aluno          integer      GENERATED BY DEFAULT AS IDENTITY,
    id_curso          smallint     NOT NULL,
    id_curriculo      integer      NOT NULL,
    matricula_aluno   varchar(12)  NOT NULL,
    nome_aluno        varchar(120) NOT NULL,
    cpf_aluno         char(11)     NOT NULL,              -- só dígitos; DV é regra de aplicação
    email_aluno       varchar(120) NOT NULL,
    nascimento_aluno  date         NOT NULL,
    ingresso_aluno    date         NOT NULL,
    ativo_aluno       boolean      NOT NULL DEFAULT true, -- desligamento é false, nunca DELETE

    CONSTRAINT pk_aluno PRIMARY KEY (id_aluno),
    CONSTRAINT uq_aluno_matricula UNIQUE (matricula_aluno),
    CONSTRAINT uq_aluno_cpf       UNIQUE (cpf_aluno),
    CONSTRAINT uq_aluno_email     UNIQUE (email_aluno),
    CONSTRAINT ck_aluno_matricula_preenchida CHECK (length(btrim(matricula_aluno)) > 0),
    CONSTRAINT ck_aluno_nome_preenchido      CHECK (length(btrim(nome_aluno)) > 0),
    CONSTRAINT ck_aluno_cpf_valido           CHECK (cpf_aluno ~ '^[0-9]{11}$'),
    CONSTRAINT ck_aluno_email_minusculo      CHECK (email_aluno = lower(email_aluno)),
    CONSTRAINT ck_aluno_email_formato        CHECK (email_aluno LIKE '%_@_%._%'),
    CONSTRAINT ck_aluno_ingresso_apos_nascimento CHECK (ingresso_aluno > nascimento_aluno),
    CONSTRAINT ck_aluno_nascimento_plausivel
        CHECK (nascimento_aluno BETWEEN '1900-01-01' AND current_date),
    CONSTRAINT fk_aluno_curriculo_curso                     -- composta: currículo tem de ser do curso do aluno
        FOREIGN KEY (id_curriculo, id_curso)
        REFERENCES tb_curriculo (id_curriculo, id_curso)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_aluno_curso FOREIGN KEY (id_curso) REFERENCES tb_curso (id_curso)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE tb_curriculo_disciplina (
