CREATE TABLE tb_feriado (
    id_feriado         integer      GENERATED BY DEFAULT AS IDENTITY,
    id_campus          smallint,                          -- NULL = feriado nacional
    descricao_feriado  varchar(120) NOT NULL,
    data_feriado       date         NOT NULL,

    CONSTRAINT pk_feriado PRIMARY KEY (id_feriado),
    CONSTRAINT uq_feriado_data_campus                       -- NULLS NOT DISTINCT: nacional não duplica na data
        UNIQUE NULLS NOT DISTINCT (data_feriado, id_campus),
    CONSTRAINT ck_feriado_descricao_preenchida CHECK (length(btrim(descricao_feriado)) > 0),
    CONSTRAINT fk_feriado_campus FOREIGN KEY (id_campus) REFERENCES tb_campus (id_campus)
        ON DELETE RESTRICT ON UPDATE CASCADE
