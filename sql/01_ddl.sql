    CONSTRAINT pk_curso PRIMARY KEY (id_curso),
    CONSTRAINT uq_curso_codigo UNIQUE (codigo_curso),
    CONSTRAINT ck_curso_codigo_preenchido CHECK (length(btrim(codigo_curso)) > 0),
    CONSTRAINT ck_curso_nome_preenchido   CHECK (length(btrim(nome_curso)) > 0),
    CONSTRAINT ck_curso_ch_total_positiva CHECK (ch_total_curso > 0),
    CONSTRAINT fk_curso_campus FOREIGN KEY (id_campus) REFERENCES tb_campus (id_campus)
        ON DELETE RESTRICT ON UPDATE CASCADE
