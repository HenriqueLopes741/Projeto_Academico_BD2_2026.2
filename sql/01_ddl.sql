-- Pré-condição: base `matricula` vazia (docker compose down -v && up -d).
-- Não é idempotente de propósito: reset = recriar a base.
--
-- Nomes:  tabela tb_<nome> · atributo <atributo>_<tabela> · PK id_<tabela>
--         FK = nome da PK referenciada · constraint pk_/uq_/ck_/fk_/ex_<tabela>_<assunto>
-- Colunas: PK → FK → texto → numéricos → demais (data, boolean, enum, jsonb)
-- Constraints: PK → UQ → CK → FK, dentro de cada CREATE TABLE.
-- FKs: ON UPDATE CASCADE sempre; ON DELETE RESTRICT, salvo onde comentado.
-- Tabelas em ordem de dependência: cada FK aponta para uma tabela já criada.

-- =====================================================================
-- PARTE 1 — EXTENSÃO, TIPOS E DOMÍNIOS
-- =====================================================================

CREATE EXTENSION IF NOT EXISTS btree_gist;  -- '=' em colunas escalares no EXCLUDE de tb_turma_horario

-- Enums: a ordem dos rótulos é a ordem do ORDER BY.
CREATE TYPE tipo_sala_t  AS ENUM ('teorica', 'laboratorio', 'auditorio');
CREATE TYPE turno_t      AS ENUM ('matutino', 'vespertino', 'noturno');
CREATE TYPE vinculo_t    AS ENUM ('pre_requisito', 'co_requisito', 'equivalencia');
CREATE TYPE tipo_disc_t  AS ENUM ('obrigatoria', 'optativa', 'eletiva');
CREATE TYPE status_mat_t AS ENUM ('ativa', 'trancada', 'cancelada', 'concluida');
CREATE TYPE situacao_t   AS ENUM ('cursando', 'trancada', 'aprovado',
                                  'reprovado_nota', 'reprovado_falta', 'reprovado_nota_falta');

-- Domínios: o CHECK aceita NULL (nota não lançada não é violação).
CREATE DOMAIN nota_t AS numeric(4,2)        -- mesmo tipo de media_final_historico
    CONSTRAINT ck_nota_t_faixa CHECK (VALUE >= 0 AND VALUE <= 10);
CREATE DOMAIN pct_t  AS numeric(5,2)        -- (5,2) para caber 100,00
    CONSTRAINT ck_pct_t_faixa CHECK (VALUE >= 0 AND VALUE <= 100);

-- timerange não é nativo. A função de distância orienta o particionamento do GiST.
CREATE FUNCTION time_subtype_diff(x time, y time)
RETURNS float8
AS $$
    SELECT EXTRACT(EPOCH FROM (x - y))::float8;
$$ LANGUAGE sql IMMUTABLE STRICT;

CREATE TYPE timerange AS RANGE (
    subtype      = time,                    -- hora de parede, sem fuso
    subtype_diff = time_subtype_diff
);

COMMENT ON TYPE timerange IS
    'Faixa de horário de aula, sempre semiaberta [): 10:40 não conflita com 10:40.';

