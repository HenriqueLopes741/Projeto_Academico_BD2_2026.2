CREATE TABLE tb_sala (
    id_sala          integer     GENERATED BY DEFAULT AS IDENTITY,
    id_campus        smallint    NOT NULL,
    codigo_sala      varchar(10) NOT NULL,
    capacidade_sala  smallint    NOT NULL,
    tipo_sala        tipo_sala_t NOT NULL,

    CONSTRAINT pk_sala PRIMARY KEY (id_sala),
    CONSTRAINT uq_sala_campus_codigo UNIQUE (id_campus, codigo_sala),  -- código único por campus, não global
    CONSTRAINT ck_sala_codigo_preenchido CHECK (length(btrim(codigo_sala)) > 0),
    CONSTRAINT ck_sala_capacidade        CHECK (capacidade_sala BETWEEN 1 AND 1000),
    CONSTRAINT fk_sala_campus FOREIGN KEY (id_campus) REFERENCES tb_campus (id_campus)
        ON DELETE RESTRICT ON UPDATE CASCADE
