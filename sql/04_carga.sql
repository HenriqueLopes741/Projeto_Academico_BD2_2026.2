--
-- Decisões da carga:
--
-- 1. Um módulo por semestre. Os dois cursos têm 8 módulos (1A..4B), um por
--    semestre. Com os 4 períodos carregados, 2026/2 é o módulo 2B:
--        2025/1 -> 1A (periodo 1)    2025/2 -> 1B (periodo 2)
--        2026/1 -> 2A (periodo 3)    2026/2 -> 2B (periodo 4, em andamento)
--    periodo_curriculo_disciplina guarda esse número (1 a 8).
--
-- 2. Tudo é determinístico: sem random(). Rodar a carga duas vezes em bancos
--    limpos gera o mesmo banco, o que permite comparar EXPLAIN antes e
--    depois dos índices.
--
-- 3. Sem ids explícitos: as colunas são GENERATED BY DEFAULT, e inserir um id
--    na mão não avança a sequence. Todas as FKs são resolvidas por chave
--    natural (nome, código, matrícula) via JOIN.
--
-- 4. Dados fictícios: professores e alunos são inventados. Disciplinas,
--    módulos e cargas horárias seguem as grades; onde a grade só informa o
--    total do módulo, a carga foi distribuída para fechar esse total.
--
-- Ordem (respeita as FKs):
--   tb_campus, tb_periodo_letivo, tb_professor, tb_sala
