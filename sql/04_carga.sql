              'Oliveira','Pacheco','Pereira','Ramos','Ribeiro','Rocha','Santana',
              'Teixeira','Vasconcelos','Xavier'] AS meios,
        ARRAY['Almeida','Araújo','Azevedo','Batista','Borges','Brandão','Campos',
